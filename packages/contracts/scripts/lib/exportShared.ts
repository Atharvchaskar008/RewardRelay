import fs from "fs";
import path from "path";
import * as prettier from "prettier";
import type { HardhatRuntimeEnvironment } from "hardhat/types";
import { CATEGORIES } from "./config";
import { readPublicRecords } from "./records";

/**
 * Generates the typed modules of packages/shared from the build artifacts, the committed deployment
 * records and the category configuration, so the app and the scripts can never disagree on an ABI,
 * an address or a category id. Local deployments are not exported: the app reads them from env.
 */

const SHARED_SRC = path.join(__dirname, "..", "..", "..", "shared", "src");
const HEADER = "// Generated by packages/contracts/scripts/deploy.ts. Do not edit by hand.\n\n";

async function writeFormatted(file: string, source: string): Promise<void> {
  const options = (await prettier.resolveConfig(file)) ?? {};
  fs.writeFileSync(file, await prettier.format(source, { ...options, filepath: file }));
}

export async function exportShared(hre: HardhatRuntimeEnvironment): Promise<string[]> {
  fs.mkdirSync(SHARED_SRC, { recursive: true });

  const escrow = await hre.artifacts.readArtifact("RelayEscrow");
  const sbt = await hre.artifacts.readArtifact("ReputationSBT");
  const abis = path.join(SHARED_SRC, "abis.ts");
  await writeFormatted(
    abis,
    `${HEADER}export const relayEscrowAbi = ${JSON.stringify(escrow.abi)} as const;\n\n` +
      `export const reputationSbtAbi = ${JSON.stringify(sbt.abi)} as const;\n`,
  );

  const networks: Record<string, unknown> = {};
  for (const record of readPublicRecords()) {
    const contracts: Record<string, unknown> = {};
    for (const [name, info] of Object.entries(record.contracts)) {
      contracts[name] = {
        address: info.address,
        blockNumber: info.blockNumber,
        txHash: info.txHash,
      };
    }
    networks[record.network] = {
      chainId: record.chainId,
      deployer: record.deployer,
      commit: record.commit,
      contracts,
    };
  }
  const deployments = path.join(SHARED_SRC, "deployments.ts");
  await writeFormatted(
    deployments,
    `${HEADER}/** Contracts deployed by packages/contracts/scripts/deploy.ts, per network. */\n` +
      `export const deployments = ${JSON.stringify(networks)} as const;\n\n` +
      `export type NetworkName = keyof typeof deployments;\n`,
  );

  const categories = path.join(SHARED_SRC, "categories.ts");
  const rows = CATEGORIES.map(({ id, key, dealType, demo, production }) => ({
    id,
    key,
    dealType: dealType === 0 ? "BuyForYou" : "PassOn",
    demo,
    production,
  }));
  await writeFormatted(
    categories,
    `${HEADER}/** Category ids and policy windows (seconds) configured on-chain by scripts/configure.ts. */\n` +
      `export const CATEGORIES = ${JSON.stringify(rows)} as const;\n\n` +
      `export type CategoryKey = (typeof CATEGORIES)[number]["key"];\n`,
  );

  return [abis, deployments, categories];
}
